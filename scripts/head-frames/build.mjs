// Rebuild the hero's head from the hand-editable text frames.
//
//   node scripts/head-frames/build.mjs      (or: npm run build:head-frames)
//
// Reads scripts/head-frames/frames/step-000.txt ... step-NNN.txt, one file per step of the turn
// (step 0 faces the viewer; each following step turns the head a little further toward screen-right
// until step N-1 is just short of a full circle). Writes:
//   src/lib/data/headSpin.ts   all the frames, shipped lazily after the page loads
//   src/lib/data/headRest.ts   step 0, inlined so the hero has a head on first paint
//   scripts/head-frames/preview.html   a standalone page to scrub through every step (git-ignored)
//
// Rules the files must follow: plain text, one row per line, 58 rows, at most 88 columns, no tabs.
// Short rows and missing rows are padded with spaces; an over-long row is an error rather than a
// silent crop.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import zlib from 'node:zlib';

const COLS = 88;
const ROWS = 58;

const here = path.dirname(url.fileURLToPath(import.meta.url));
const framesDir = path.join(here, 'frames');
const dataDir = path.join(here, '..', '..', 'src', 'lib', 'data');

const files = fs.existsSync(framesDir) ? fs.readdirSync(framesDir).filter((f) => /^step-\d+\.txt$/.test(f)).sort() : [];
if (!files.length) {
	console.error('No frames found. Run: node scripts/head-frames/export.mjs');
	process.exit(1);
}
files.forEach((f, i) => {
	const want = `step-${String(i).padStart(3, '0')}.txt`;
	if (f !== want) {
		console.error(`Expected ${want} but found ${f}. Steps must be numbered 000..${String(files.length - 1).padStart(3, '0')} with no gaps.`);
		process.exit(1);
	}
});

const problems = [];
const warnings = [];
const texts = files.map((f) => {
	const raw = fs.readFileSync(path.join(framesDir, f), 'utf8').replace(/\r\n?/g, '\n');
	const lines = raw.split('\n');
	if (lines.length && lines[lines.length - 1] === '') lines.pop();
	if (lines.length > ROWS) {
		const extra = lines.slice(ROWS).filter((l) => l.trim());
		if (extra.length) problems.push(`${f}: ${lines.length} rows, the most allowed is ${ROWS}`);
		lines.length = ROWS;
	}
	while (lines.length < ROWS) lines.push('');
	return lines
		.map((line, r) => {
			if (line.includes('\t')) problems.push(`${f} row ${r + 1}: contains a tab; use spaces`);
			const trimmed = line.replace(/\s+$/, '');
			if (trimmed.length > COLS) problems.push(`${f} row ${r + 1}: ${trimmed.length} columns, the most allowed is ${COLS}`);
			return trimmed.padEnd(COLS);
		})
		.join('\n');
});
if (problems.length) {
	console.error(problems.slice(0, 20).join('\n') + (problems.length > 20 ? `\n...and ${problems.length - 20} more` : ''));
	console.error('\nNothing was written. Fix the files above and run this again.');
	process.exit(1);
}

// Identical frames are stored once.
const order = [];
const unique = [];
const seen = new Map();
for (const t of texts) {
	if (!seen.has(t)) {
		seen.set(t, unique.length);
		unique.push(t);
	}
	order.push(seen.get(t));
}

fs.writeFileSync(
	path.join(dataDir, 'headSpin.ts'),
	'// Generated by scripts/head-frames/build.mjs from the text files in scripts/head-frames/frames/.\n' +
		'// Edit those files, not this one.\n' +
		`export const SPIN_STEPS = ${files.length};\n` +
		`/** For each of SPIN_STEPS evenly spaced angles (0 = facing the viewer, turning toward screen-right), which frame to show. */\n` +
		`export const spinOrder: number[] = ${JSON.stringify(order)};\n` +
		`export const spinFrames: string[] = ${JSON.stringify(unique)};\n`
);
fs.writeFileSync(
	path.join(dataDir, 'headRest.ts'),
	'// Generated by scripts/head-frames/build.mjs. The facing-the-viewer frame (step 0), inlined so the\n' +
		'// hero has a portrait before the full set loads.\n' +
		`export const HEAD_COLS = ${COLS};\n` +
		`export const headRest = ${JSON.stringify(unique[order[0]])};\n`
);

